#!/usr/bin/env bash
# Detect usages of Kiwi 1.4 APIs, dependencies and properties that need changes for Kiwi 1.5, and of Kiwi-Vue 1.x in
# frontends (Kiwi-Vue 2.0). Prints a Markdown report grouped by the phases of the kiwi-upgrade skill (2-7, 9); each
# finding is "path:line: source line".
#
# Usage: detect-1.4-usages.sh [project-dir]   (default: current directory)
#
# The checks are grep heuristics: they find candidates, not certainties. Review every finding
# against references/migration-1.5.md before changing code.
set -u

PROJECT_DIR="${1:-.}"
cd "$PROJECT_DIR" || { echo "Project directory not found: $PROJECT_DIR" >&2; exit 2; }

EXCLUDES=(
  --exclude-dir=.git
  --exclude-dir=build
  --exclude-dir=.gradle
  --exclude-dir=node_modules
  --exclude-dir=out
  --exclude-dir=target
  --exclude-dir=dist
  --exclude-dir=.idea
  --exclude-dir=.kotlin
  --exclude-dir=.claude
)
BUILD_FILES=(
  --include='*.gradle.kts'
  --include='*.gradle'
  --include='pom.xml'
  --include='*.toml'
)
SOURCES=(
  --include='*.kt'
  --include='*.java'
)
CONFIG=(
  --include='application*.yml'
  --include='application*.yaml'
  --include='application*.properties'
)
FRONTEND=(
  --include='*.ts'
  --include='*.tsx'
  --include='*.js'
  --include='*.jsx'
  --include='*.vue'
  --include='*.svelte'
)
PACKAGE=(
  --include='package.json'
)
MESSAGES=(
  --include='*.json'
  --include='*.yaml'
  --include='*.yml'
  --include='*.ts'
  --include='*.js'
  --include='*.vue'
)

TOTAL=0

# check <title> <hint> <regex> <include-args...>
check() {
  local title="$1" hint="$2" regex="$3"
  shift 3

  local matches
  matches=$(grep -rnIE "${EXCLUDES[@]}" "$@" -e "$regex" . 2>/dev/null | sed -e 's|^\./||' | cut -c1-220)
  [ -z "$matches" ] && return

  local count
  count=$(printf '%s\n' "$matches" | wc -l | tr -d ' ')
  TOTAL=$((TOTAL + count))
  printf '### %s (%s)\n\n%s\n\n```\n%s\n```\n\n' "$title" "$count" "$hint" "$matches"
}

section() {
  printf '## %s\n\n' "$1"
}

printf '# Kiwi 1.4 usages in %s\n\n' "$(pwd)"
printf 'Generated by detect-1.4-usages.sh. Heuristic findings: verify each one against the migration guide.\n\n'

section "Phase 2: Build and dependencies"
check "Kiwi bundle artifact" \
  "\`de.kiwi-framework:kiwi-bundle\` is published as \`de.kiwi-framework:kiwi-framework\`." \
  'kiwi-bundle' "${BUILD_FILES[@]}"
check "Spring Boot 3 / Kotlin < 2.3 versions" \
  "Kiwi 1.5 requires Spring Boot 4.1 and Kotlin 2.3 (Java 21)." \
  '(spring-?boot|springframework\.boot)[^0-9]{0,40}["'"'"'=: ]3\.[0-9]+(\.[0-9]+)?|kotlin[^0-9]{0,40}["'"'"'=: ]2\.[0-2]\.[0-9]+' \
  "${BUILD_FILES[@]}" --include='gradle.properties'
check "Renamed Spring Boot starters" \
  "\`spring-boot-starter-web\` → \`spring-boot-starter-webmvc\`, \`spring-boot-starter-json\` → \`spring-boot-starter-jackson\`." \
  'spring-boot-starter-(web|json)(["'"'"':)]|$)' "${BUILD_FILES[@]}"
check "Liquibase without starter" \
  "Replace \`org.liquibase:liquibase-core\` by \`spring-boot-starter-liquibase\`, otherwise migrations silently stop running." \
  'liquibase-core' "${BUILD_FILES[@]}"
check "JPA model generator" \
  "\`hibernate-jpamodelgen\` → \`org.hibernate.orm:hibernate-processor\`." \
  'hibernate-jpamodelgen' "${BUILD_FILES[@]}"
check "Testcontainers 1 artifacts" \
  "Testcontainers 2 prefixes module artifacts: \`org.testcontainers:mysql\` → \`org.testcontainers:testcontainers-mysql\`." \
  'org\.testcontainers:(junit-jupiter|mariadb|mysql|postgresql|minio|localstack|kafka|mongodb)\b' "${BUILD_FILES[@]}"
check "Jackson 2 dependencies" \
  "Jackson 3 artifacts use the group \`tools.jackson.*\` (annotations stay in \`com.fasterxml.jackson.core:jackson-annotations\`)." \
  'com\.fasterxml\.jackson\.(module|datatype|dataformat|core:jackson-(databind|core))' "${BUILD_FILES[@]}"
if { [ -f build.gradle.kts ] || [ -f build.gradle ]; } && [ ! -f gradlew ]; then
  TOTAL=$((TOTAL + 1))
  printf '### Gradle wrapper missing (1)\n\n%s\n\n' \
    "The project has no Gradle wrapper: make sure the Gradle version used supports Spring Boot 4.1 (Gradle 8.14+ or 9), ideally by adding a wrapper."
fi
check "Test slices" \
  "Test slices need their own starters (\`spring-boot-starter-data-jpa-test\`, \`spring-boot-starter-webmvc-test\`) and moved packages." \
  '@(DataJpaTest|WebMvcTest|AutoConfigureMockMvc|AutoConfigureTestDatabase)\b' "${SOURCES[@]}"

section "Phase 3: Application setup"
check "Imported Kiwi configurations" \
  "Kiwi 1.5 uses auto-configuration: remove \`@Import\` of Kiwi configurations." \
  'Kiwi(Framework|AuditLog|Storage|Web|Mjml)Configuration\b|KiwiOpenApiConfig\b|KiwiManagementSecurityConfig\b' "${SOURCES[@]}"
check "Entity and repository scanning" \
  "Remove \`@EntityScan\`/\`@EnableJpaRepositories\` that only exist to list Kiwi packages; keep the ones for your own packages." \
  '@(EntityScan|EnableJpaRepositories)\b' "${SOURCES[@]}"
check "Renamed Kiwi packages" \
  "\`de.kiwi.auditLog\` → \`de.kiwi.auditlog\`, \`de.kiwi.framework.mjml\` → \`de.kiwi.mjml\`." \
  'de\.kiwi\.auditLog|de\.kiwi\.framework\.mjml' "${SOURCES[@]}" "${CONFIG[@]}"
check "Moved Spring Boot packages" \
  "Spring Boot 4 moved classes into technology modules (e.g. \`org.springframework.boot.persistence.autoconfigure.EntityScan\`)." \
  'org\.springframework\.boot\.(autoconfigure\.domain\.EntityScan|test\.autoconfigure\.(orm\.jpa|web\.servlet))' "${SOURCES[@]}"

section "Phase 4: Jackson 3"
check "Jackson 2 imports" \
  "\`com.fasterxml.jackson.{core,databind,module}\` → \`tools.jackson.*\`; \`com.fasterxml.jackson.annotation\` stays." \
  'import com\.fasterxml\.jackson\.(core|databind|module|datatype)' "${SOURCES[@]}"
check "Renamed Jackson API" \
  "\`TextNode\` → \`StringNode\`, \`asText()\` → \`asString()\`, \`fieldNames()\` → \`propertyNames()\`, \`JsonMappingException\` → \`DatabindException\`, \`registerModule\` → mapper builder." \
  '\bTextNode\b|\.asText\(|\.fieldNames\(\)|JsonMappingException|\.registerModule\(' "${SOURCES[@]}"

JSON_MAP=$(grep -rlIE "${EXCLUDES[@]}" "${SOURCES[@]}" -e 'JsonNode' . 2>/dev/null | xargs -r grep -nHE '\.map *\{' 2>/dev/null | sed -e 's|^\./||' | cut -c1-220)
if [ -n "$JSON_MAP" ]; then
  COUNT=$(printf '%s\n' "$JSON_MAP" | wc -l | tr -d ' ')
  TOTAL=$((TOTAL + COUNT))
  printf '### `.map { }` in files using JsonNode (%s)\n\n%s\n\n```\n%s\n```\n\n' "$COUNT" \
    "Pitfall: \`JsonNode.map(…)\` is a Jackson 3 member function and wins over \`Iterable.map\`. Iterate array elements using \`node.values().map { … }\`. Most matches are unrelated: check the receiver type." \
    "$JSON_MAP"
fi

section "Phase 5: Kiwi API"
check "Generic commands (1.4 style)" \
  "Generic create/update commands declare body properties now; handlers receive the typed command. See references/generic-commands.md." \
  '\b(CreateBody|UpdateBody|entityFieldset|jsonBody)\b|entityDetails\(|\.jsonDetails\b' "${SOURCES[@]}"
check "Generic body accessors (1.4 style)" \
  "\`create.require(...)\`, \`update.patchField(...)\` etc. become property reads and \`patchFields\`/\`ifPatched\`." \
  '\b(create|update)\.(require|get|patch|patchField|patchNotNull)\b|\b(create|update)\[' "${SOURCES[@]}"
check "Null checks on handler results in tests" \
  "\`CommandHandler.handle\` returns a non-null \`DomainResult\` in 1.5: remove \`?: fail(…)\` and similar null handling." \
  '\.handle\(.*(\?:|!!)' "${SOURCES[@]}"
check "Generic create entityId overrides" \
  "\`GenericCreate.entityId(entity)\` defaults to \`BaseEntity.id\`: remove trivial overrides." \
  'override fun entityId\(' "${SOURCES[@]}"
check "Removed JWT support" \
  "JWT support was removed: use Spring Security's OAuth2 resource server instead." \
  'AuthenticationTokenService|JwtTokenService|BearerTokenAuthenticationFilter|_accessToken' "${SOURCES[@]}" "${FRONTEND[@]}"
check "Mail template renderers" \
  "\`MailTemplateRenderer\` is an ordered SPI; the pipeline consists of all renderer beans." \
  'MailTemplateRenderer' "${SOURCES[@]}"
check "Changed nullness signatures" \
  "JSpecify nullness: \`QueryBuilder.Executor<R : Any>\`, \`PageResult.fromPage<T : Any>\`, \`findPage<E, N : Any>\`, non-null \`CriteriaQuery\` parameters." \
  'AccessControlSpecification|GenericEntityFilter|PageResult\.fromPage|QueryBuilder\.Executor|\.findPage<' "${SOURCES[@]}"
check "Custom DetailsProvider implementations" \
  "\`DetailsProvider.toDetails(value, user: UserDescriptor?)\` takes the user as second parameter (\`null\`: current user)." \
  'DetailsProvider(<[^>]*>)?\s*\{|[:,]\s*DetailsProvider\b|fun toDetails\(' "${SOURCES[@]}"
check "Custom TransactionService implementations" \
  "\`TransactionService.writeNew\` was added (default: \`write\`); implement it with REQUIRES_NEW semantics if errors should survive rollbacks." \
  ':\s*TransactionService\b' "${SOURCES[@]}"

section "Phase 6: Configuration properties"
check "Renamed or removed properties" \
  "\`kiwi.enable-audit-logging\` → \`kiwi.audit-log.enabled\`, \`kiwi.audit-log-console\` → \`kiwi.audit-log.console\`, \`kiwi.mail.template-renderers\` and \`kiwi.jwt.*\` removed." \
  'enable-audit-logging|enableAuditLogging|audit-log-console|auditLogConsole|template-renderers|kiwi\.jwt|^\s*jwt:' "${CONFIG[@]}"
if grep -rqIE "${EXCLUDES[@]}" "${BUILD_FILES[@]}" -e 'kiwi-storage' . 2>/dev/null \
  && ! grep -rqIE "${EXCLUDES[@]}" "${CONFIG[@]}" -e '(^|\.)provider\s*[:=]' . 2>/dev/null; then
  TOTAL=$((TOTAL + 1))
  printf '### Storage provider not configured (1)\n\n%s\n\n' \
    "The project uses \`kiwi-storage\` without \`kiwi.storage.provider\`: it has no default anymore (was \`s3\`), and the application fails to start without it, unless it declares its own \`FileStorageService\` bean. Configure the provider explicitly (\`none\` discards file data)."
fi
check "Local file storage" \
  "The \`local\` provider requires \`kiwi.storage.local.token.secret-key\` (Base64, at least 256 bits); signed URIs issued by 1.4 become invalid." \
  'provider:\s*[Ll]ocal|storage\.provider\s*=\s*[Ll]ocal' "${CONFIG[@]}"

section "Phase 7: HTTP clients and endpoints"
check "PUT requests (frontends, HTTP clients, tests)" \
  "Generic updates use \`PATCH /<entity>/{id}\` instead of \`PUT\`. Only requests to generic entity endpoints must change." \
  '(method:\s*["'"'"']PUT|\.put\(|HttpMethod\.PUT|\bput\(["'"'"'/]|MockMvcRequestBuilders\.put|@PutMapping)' "${SOURCES[@]}" "${FRONTEND[@]}"

section "Phase 7: Kiwi-Vue frontends (1.x → 2.0, see references/kiwi-vue-2.md)"
check "Kiwi-Vue 1.x dependency" \
  "Kiwi-Vue 2.0 is required for Kiwi-Server 1.5 (it sends \`PATCH\` for updates). Upgrade the frontend together with the server." \
  '"@werdenktwas/kiwi-vue"\s*:\s*"[~^]?1\.' "${PACKAGE[@]}"
check "CRUD services with two type parameters" \
  "\`basicCrudService\`/\`CrudService\` take the create and update body types as third and fourth type parameter (\`ICreate…\`, \`IUpdate…\` of the generated model)." \
  '(basicCrudService|CrudService|CrudServiceClass)<\s*[^,<>]+(<[^<>]*>)?\s*,\s*[^,<>]+\s*>' "${FRONTEND[@]}"
check "create/update with body type arguments" \
  "\`create<POST, R>(body)\`/\`update<PUT, R>(id, body)\` become \`create<R>(body)\`/\`update<R>(id, body)\`. Updates are partial: send only changed properties, never \`id\` or undeclared keys." \
  '\.(create|update)<[^>(]*,[^>(]*>\s*\(' "${FRONTEND[@]}"
check "Whole objects in update bodies" \
  "Kiwi-Server 1.5 rejects unknown keys (e.g. \`id\`) with \`entity-body-invalid\`: check that update bodies don't spread loaded entities." \
  '\.update(<[^>]*>)?\(\s*[^,]+,\s*\{\s*\.\.\.' "${FRONTEND[@]}"
check "Custom API requests" \
  "Request paths are relative to the API URL now, also with a leading slash; pass a \`URL\` for paths outside the API. \`jsonRequest\` takes \`(path, body, method, params?, init?)\`. \`FetchApi\` takes \`(baseUrl, fetch?, preprocessor?)\`, prefer \`createApi(options)\`." \
  '\.(request|jsonRequest)\(\s*["'"'"'`]/|new FetchApi\(' "${FRONTEND[@]}"
check "Removed or changed credentials API" \
  "\`CredentialsInvalid.details\` no longer contains the credentials (use \`.credentials\`); \`UsernamePassword.userDetails\` was removed." \
  '\.userDetails\b|details\.credentials\b|details\[["'"'"']credentials' "${FRONTEND[@]}"
check "Error messages" \
  "Add messages for \`entity-body-invalid\` (or its nested codes \`entity-field-missing-value\`, \`entity-field-invalid\`, \`entity-field-unknown\`, \`entity-mismatched-input\`), \`access-denied\` (403 with body) and \`unauthorized\` (401). \`resourceErrorTransformer\`: conditions on absent details no longer match." \
  'i18nErrorTransformer|resourceErrorTransformer|["'"'"']forbidden["'"'"']\s*:' "${MESSAGES[@]}"
check "Generated TypeScript model" \
  "Regenerate the model from the Kiwi-Server 1.5 application: \`ICreate…\`/\`IUpdate…\` contain the declared body properties of the generic commands, with their JSON keys." \
  'Kiwi Framework generated Fieldset types' --include='*.ts'

section "Phase 9: Behavior changes to review (report)"
check "Roles and authorities" \
  "Security relevant: roles are the granted authorities without the \`ROLE_\` prefix now (\`kiwi.security.role-prefix\`). \`authorities(\"ADMIN\")\` stays role \`ADMIN\`. \`roles(\"ADMIN\")\` (authority \`ROLE_ADMIN\`) was role \`ROLE_ADMIN\` in 1.4 and is role \`ADMIN\` now: such users gain Kiwi admin rights. Check every user source; \`kiwi.security.role-prefix=\"\"\` keeps the 1.4 behavior." \
  '\.authorities\(|\.roles\(|hasRole\(|hasAuthority\(|ROLE_|SimpleGrantedAuthority' "${SOURCES[@]}"
check "S3 object URIs" \
  "Subdomain object URIs of non-AWS providers are \`{bucket}.{hostname}\` now; 1.4 URIs are still accepted." \
  'object-uri-type|objectUriType|s3:\s*$|kiwi\.storage\.s3' "${CONFIG[@]}"
check "Audit log" \
  "Errors of failed commands are persisted in a separate transaction after the rollback; event details are a JSON column migrated by the module's changelog (back up production databases before deploying)." \
  'kiwi-audit-log|AuditLogEntry|AuditLoggerService|detailsBinary|details_binary' "${SOURCES[@]}" "${BUILD_FILES[@]}"

printf -- '---\n\nTotal findings: %s\n' "$TOTAL"
